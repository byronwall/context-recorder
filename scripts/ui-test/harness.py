#!/usr/bin/env python3
"""Prepare and launch an isolated Context Recorder UI test library."""

from __future__ import annotations

import argparse
import json
import os
import plistlib
import shutil
import signal
import subprocess
import time
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
TMP = ROOT / "tmp" / "ui-test"
FIXTURES = TMP / "fixtures"
MARKER = FIXTURES / ".context-recorder-ui-test-fixtures"
APP = TMP / "Context Recorder UI Test.app"
PID_FILE = TMP / "ui-test.pid"
APP_ID = "com.byronwall.ContextRecorder.UITest"
SOURCE = Path.home() / "Movies" / "ContextRecorder"
REQUIRED = ("2026-10-13_00-57-10", "2026-10-13_20-48-53")
SILENT = ("2026-10-12_22-42-47", "2026-10-12_22-51-23")
SESSIONS = REQUIRED + SILENT


def fraction(value: str) -> float:
    try:
        number = float(value)
    except ValueError as error:
        raise argparse.ArgumentTypeError("timeline fraction must be a number from 0 to 1") from error
    if not 0 <= number <= 1:
        raise argparse.ArgumentTypeError("timeline fraction must be from 0 to 1")
    return number


def window_width(value: str) -> int:
    try:
        number = int(value)
    except ValueError as error:
        raise argparse.ArgumentTypeError("window width must be an integer of at least 980") from error
    if number < 980:
        raise argparse.ArgumentTypeError("window width must be at least 980")
    return number


def safe_fixture_location(destination: Path, parent: Path, source: Path) -> bool:
    destination = destination.resolve()
    parent = parent.resolve()
    source = source.resolve()
    return destination.parent == parent and destination != source and not destination.is_relative_to(source)


def process_matches(command: str, started: str, expected_command: str, expected_start: str) -> bool:
    return started == expected_start and command.startswith(expected_command + " ") and "--library " in command


def safe_remove_fixtures() -> None:
    if TMP.is_symlink() or not safe_fixture_location(FIXTURES, TMP, SOURCE):
        raise SystemExit(f"Refusing unsafe fixture destination: {FIXTURES}")
    if FIXTURES.is_symlink():
        raise SystemExit(f"Refusing unsafe fixture path: {FIXTURES}")
    if FIXTURES.exists():
        if not MARKER.is_file():
            raise SystemExit(f"Refusing to replace unmarked directory: {FIXTURES}")
        shutil.rmtree(FIXTURES)


def reject_symlinks(folder: Path) -> None:
    for path in folder.rglob("*"):
        if path.is_symlink():
            raise SystemExit(f"Fixture contains a symbolic link: {path}")


def validate_fixtures() -> None:
    if TMP.is_symlink() or FIXTURES.is_symlink() or not safe_fixture_location(FIXTURES, TMP, SOURCE):
        raise SystemExit(f"Refusing unsafe fixture path: {FIXTURES}")
    if not FIXTURES.is_dir() or MARKER.is_symlink() or not MARKER.is_file():
        raise SystemExit("Run 'prepare' first")
    reject_symlinks(FIXTURES)


def validate_app() -> None:
    if APP.is_symlink() or not APP.is_dir() or APP.resolve().parent != TMP.resolve():
        raise SystemExit(f"Run 'prepare' first; unsafe or missing app bundle: {APP}")
    reject_symlinks(APP)
    with (APP / "Contents" / "Info.plist").open("rb") as file:
        if plistlib.load(file).get("CFBundleIdentifier") != APP_ID:
            raise SystemExit("Unexpected test bundle identifier; run 'prepare' first")


def prepare() -> None:
    if PID_FILE.exists():
        raise SystemExit("Stop the harness-owned GUI app before preparing again")
    if not safe_fixture_location(FIXTURES, TMP, SOURCE):
        raise SystemExit("Fixture destination cannot be inside the real session library")
    if not SOURCE.is_dir() or SOURCE.is_symlink():
        raise SystemExit(f"Session library not found or unsafe: {SOURCE}")

    for name in SESSIONS:
        session = SOURCE / name
        if session.is_symlink() or not session.is_dir() or not (session / "session.json").is_file():
            raise SystemExit(f"Required session is missing: {session}")
        reject_symlinks(session)

    safe_remove_fixtures()
    FIXTURES.mkdir(parents=True)
    MARKER.write_text("Generated by scripts/ui-test/harness.py\n")
    for name in SESSIONS:
        shutil.copytree(SOURCE / name, FIXTURES / name)
    copied = {path.name for path in FIXTURES.iterdir()}
    expected = set(SESSIONS) | {MARKER.name}
    if copied != expected or not all((FIXTURES / name / "session.json").is_file() for name in SESSIONS):
        raise SystemExit("Fixture copy did not pass its session inventory check")
    for name in SESSIONS:
        reject_symlinks(FIXTURES / name)

    subprocess.run(["swift", "build", "-c", "debug"], cwd=ROOT, check=True)
    executable = ROOT / ".build" / "debug" / "ContextRecorder"
    if not executable.is_file():
        raise SystemExit(f"Build did not create {executable}")

    if APP.exists() or APP.is_symlink():
        if APP.is_symlink() or APP.resolve().parent != TMP.resolve():
            raise SystemExit(f"Refusing unsafe app bundle path: {APP}")
        shutil.rmtree(APP)
    contents = APP / "Contents"
    (contents / "MacOS").mkdir(parents=True)
    (contents / "Resources").mkdir()
    shutil.copy2(executable, contents / "MacOS" / "ContextRecorder")
    shutil.copy2(ROOT / "Resources" / "AppIcon.icns", contents / "Resources" / "AppIcon.icns")
    for resource in ("process_session.py", "viewer.html"):
        shutil.copy2(ROOT / "scripts" / resource, contents / "Resources" / resource)
    with (ROOT / "Resources" / "Info.plist").open("rb") as source_plist:
        info = plistlib.load(source_plist)
    info["CFBundleIdentifier"] = APP_ID
    info["CFBundleName"] = "Context Recorder UI Test"
    info["CFBundleDisplayName"] = "Context Recorder UI Test"
    with (contents / "Info.plist").open("wb") as target_plist:
        plistlib.dump(info, target_plist)
    subprocess.run(["codesign", "--force", "--sign", "-", "--identifier", APP_ID, str(APP)], check=True)
    subprocess.run(["codesign", "--verify", "--verbose=1", str(APP)], check=True)
    print(f"Fixtures: {FIXTURES}")
    print(f"GUI app:  {APP} ({APP_ID})")


def app_command(args: argparse.Namespace, executable: str) -> list[str]:
    command = [executable, "--library", str(FIXTURES.resolve())]
    for flag in ("session", "tab", "recording_fixture"):
        value = getattr(args, flag, None)
        if value is not None:
            command.extend(["--" + flag.replace("_", "-"), value])
    if args.mark is not None:
        command += ["--mark", str(args.mark)]
    if args.timeline_hover is not None:
        command += ["--timeline-hover", str(args.timeline_hover)]
    if args.window_width is not None:
        command += ["--window-width", str(args.window_width)]
    if getattr(args, "view", None) is not None:
        command += ["--view", str(args.view)]
    if getattr(args, "view_zoom", None) is not None:
        command += ["--view-zoom", str(args.view_zoom)]
    if getattr(args, "script", None) is not None:
        command += ["--script", args.script]
    if args.capture:
        command.append("--capture")
    if args.export is not None:
        command += ["--export", str(Path(args.export).expanduser().resolve())]
    # Anything after `--` goes to the app as is, e.g. `-- --seek 70 --review-mark`.
    command += [a for a in getattr(args, "app_args", None) or [] if a != "--"]
    return command


def process_identity(pid: int) -> tuple[str, str] | None:
    command = subprocess.run(["ps", "-ww", "-p", str(pid), "-o", "command="], capture_output=True, text=True)
    started = subprocess.run(["ps", "-p", str(pid), "-o", "lstart="], capture_output=True, text=True)
    if command.returncode == 0 and started.returncode == 0 and command.stdout.strip() and started.stdout.strip():
        return command.stdout.strip(), started.stdout.strip()
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return None
    except PermissionError as error:
        raise SystemExit(f"Cannot verify process {pid}; leaving it untouched") from error
    raise SystemExit(f"Cannot verify process {pid}; leaving it untouched")


def expected_process(pid: int, start_time: str) -> bool:
    identity = process_identity(pid)
    if identity is None:
        return False
    command, started = identity
    expected = str(APP / "Contents" / "MacOS" / "ContextRecorder")
    if not process_matches(command, started, expected, start_time):
        raise SystemExit(f"PID {pid} no longer belongs to this harness app; leaving it untouched")
    return True


def launch(args: argparse.Namespace) -> None:
    validate_fixtures()
    validate_app()
    if PID_FILE.exists():
        raise SystemExit(f"PID file already exists; run 'stop' first: {PID_FILE}")
    command = app_command(args, str(APP / "Contents" / "MacOS" / "ContextRecorder"))
    env = os.environ.copy()
    if args.appearance:
        env["CR_APPEARANCE"] = args.appearance
    process = subprocess.Popen(command, cwd=ROOT, env=env, start_new_session=True)
    try:
        identity = process_identity(process.pid)
        if identity is None:
            raise SystemExit("The test app exited before its process identity could be recorded")
        PID_FILE.write_text(json.dumps({"pid": process.pid, "started": identity[1]}) + "\n")
    except BaseException:
        # Popen still owns this child even if process inspection failed.
        if process.poll() is None:
            process.terminate()
            process.wait(timeout=5)
        raise
    print(f"Started test app PID {process.pid}: {APP}")
    print(f"Library: {FIXTURES}")


def stop() -> None:
    if not PID_FILE.is_file():
        raise SystemExit("No harness-owned PID file exists")
    try:
        data = json.loads(PID_FILE.read_text())
        pid = int(data["pid"])
        if pid <= 0:
            raise ValueError("PID must be positive")
        started = str(data["started"])
    except (ValueError, KeyError, TypeError, json.JSONDecodeError) as error:
        raise SystemExit(f"Invalid PID file: {PID_FILE}") from error
    if not expected_process(pid, started):
        PID_FILE.unlink()
        print(f"Test app PID {pid} has exited.")
        return
    try:
        os.kill(pid, signal.SIGTERM)
    except ProcessLookupError:
        pass
    else:
        deadline = time.monotonic() + 5
        while time.monotonic() < deadline:
            try:
                os.kill(pid, 0)
            except ProcessLookupError:
                break
            time.sleep(0.1)
        else:
            # Recheck both command and start time to guard against PID reuse.
            if expected_process(pid, started):
                try:
                    os.kill(pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
    PID_FILE.unlink()
    print(f"Stopped harness-owned PID {pid}; no process-name lookup was used.")


def swift_run(args: argparse.Namespace) -> None:
    validate_fixtures()
    command = app_command(args, "swift")
    command[1:1] = ["run", "ContextRecorder"]
    env = os.environ.copy()
    if args.appearance:
        env["CR_APPEARANCE"] = args.appearance
    subprocess.run(command, cwd=ROOT, env=env, check=True)


def check() -> None:
    validate_fixtures()
    fixture = FIXTURES / REQUIRED[0]
    if not (fixture / "session.json").is_file():
        raise SystemExit(f"Required fixture is missing: {fixture}")
    subprocess.run(["python3", str(ROOT / "scripts" / "check-transcript.py")], cwd=ROOT, check=True)
    subprocess.run(["swift", "run", "ContextRecorder", "--library", str(fixture), "--check-previews"], cwd=ROOT, check=True)


def self_check() -> None:
    assert safe_fixture_location(TMP / "fixtures", TMP, SOURCE)
    assert not safe_fixture_location(SOURCE / "fixtures", SOURCE, SOURCE)
    assert not safe_fixture_location(TMP / "fixtures", TMP / "other", SOURCE)
    exe = str(APP / "Contents" / "MacOS" / "ContextRecorder")
    valid = f"{exe} --library {FIXTURES} --session 2026-10-13_00-57-10"
    assert process_matches(valid, "today", exe, "today")
    assert not process_matches("/Applications/Context Recorder.app/Contents/MacOS/ContextRecorder --library x", "today", exe, "today")
    assert not process_matches(valid, "yesterday", exe, "today")
    assert not process_matches("/usr/bin/python --library x", "today", exe, "today")
    args = argparse.Namespace(session=None, tab=None, recording_fixture=None, mark=None, export=None, timeline_hover=0.5, window_width=980, capture=False)
    command = app_command(args, "ContextRecorder")
    assert command[command.index("--timeline-hover"):command.index("--timeline-hover") + 2] == ["--timeline-hover", "0.5"]
    assert command[command.index("--window-width"):command.index("--window-width") + 2] == ["--window-width", "980"]
    args.capture = True
    assert app_command(args, "ContextRecorder").count("--capture") == 1
    print("Fixture path and process identity gates passed.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("prepare", help="rebuild fixture copies and the isolated debug app")
    launch_parser = commands.add_parser("launch", help="launch the isolated GUI app")
    launch_parser.add_argument("--session", choices=SESSIONS)
    launch_parser.add_argument("--tab", choices=("marks", "transcript", "page", "activity"))
    launch_parser.add_argument("--recording-fixture", choices=SESSIONS)
    launch_parser.add_argument("--mark", type=int)
    launch_parser.add_argument("--timeline-hover", type=fraction, help="show the timeline hover card at a fraction from 0 to 1")
    launch_parser.add_argument("--window-width", type=window_width, help="set test window width in points (minimum 980)")
    launch_parser.add_argument("--export", help="open export for this project folder")
    launch_parser.add_argument("--capture", action="store_true", help="enable isolated production capture for fixture-library output")
    launch_parser.add_argument("--appearance", choices=("light", "dark"))
    launch_parser.add_argument("--view", type=int, help="open this mark's image in the image viewer")
    launch_parser.add_argument("--view-zoom", type=float, help="zoom the image viewer to this percent")
    launch_parser.add_argument("--script", help="in-app input steps; see Library/DevScript.swift")
    launch_parser.add_argument("app_args", nargs=argparse.REMAINDER, help="extra app flags after --")
    run_parser = commands.add_parser("run", help="run the fixture with swift run")
    run_parser.add_argument("--session", choices=SESSIONS)
    run_parser.add_argument("--tab", choices=("marks", "transcript", "page", "activity"))
    run_parser.add_argument("--recording-fixture", choices=SESSIONS)
    run_parser.add_argument("--mark", type=int)
    run_parser.add_argument("--timeline-hover", type=fraction, help="show the timeline hover card at a fraction from 0 to 1")
    run_parser.add_argument("--window-width", type=window_width, help="set test window width in points (minimum 980)")
    run_parser.add_argument("--export", help="open export for this project folder")
    run_parser.add_argument("--capture", action="store_true", help="enable isolated production capture for fixture-library output")
    run_parser.add_argument("--appearance", choices=("light", "dark"))
    run_parser.add_argument("--view", type=int, help="open this mark's image in the image viewer")
    run_parser.add_argument("--view-zoom", type=float, help="zoom the image viewer to this percent")
    run_parser.add_argument("--script", help="in-app input steps; see Library/DevScript.swift")
    run_parser.add_argument("app_args", nargs=argparse.REMAINDER, help="extra app flags after --")
    commands.add_parser("stop", help="stop only the PID started by this harness")
    commands.add_parser("self-check", help="check fixture path and process identity gates")
    commands.add_parser("check", help="check transcript starts and preview frame changes")
    args = parser.parse_args()
    if args.command == "prepare":
        prepare()
    elif args.command == "launch":
        launch(args)
    elif args.command == "run":
        swift_run(args)
    elif args.command == "self-check":
        self_check()
    elif args.command == "check":
        check()
    else:
        stop()


if __name__ == "__main__":
    main()
